// Writes docs/curriculum-audit/grade-N-<subject>.md: every curriculum statement, and which lesson
// steps, problems and key terms teach it. Use it to check coverage (nothing missing) and
// fidelity (everything on a page traces back to a listed statement). One file per grade and
// subject, so work on different subjects never edits the same file.
// Usage: npm run audit                 every grade and subject with content
//        npm run audit -- grade-6/math one grade and subject
import { mkdirSync, writeFileSync } from 'node:fs';
import { allOutcomes, loadConcepts, outcomeStatements, resolveRef, gradeRank, gradesWithContent, roadmap } from '../src/lib/content.ts';
import { SUBJECTS, type SubjectInfo } from '../src/site.ts';

const arg = /^grade-(\d)(?:\/([a-z-]+))?$/.exec(process.argv[2] ?? '');
const grades = arg ? [Number(arg[1])] : gradesWithContent();
mkdirSync('docs/curriculum-audit', { recursive: true });

for (const GRADE of grades) {
  for (const s of SUBJECTS.filter((x) => (!arg?.[2] || x.slug === arg[2]) && roadmap(GRADE)[x.slug].length)) audit(GRADE, s);
}

function audit(GRADE: number, s: SubjectInfo) {
  const concepts = loadConcepts(GRADE).filter((c) => c.subject === s.slug);
  /** "subject|outcome|ref" → places that teach it */
  const uses = new Map<string, string[]>();
  const earlier: string[] = [];

  for (const c of concepts) {
    const note = (refs: string[], where: string) => {
      for (const r of refs) {
        const st = resolveRef(c, r);
        if (gradeRank(st.grade) < GRADE) {
          earlier.push(`| ${c.subject}/${c.id} | ${where} | Grade ${st.grade.toUpperCase()} ${st.outcomeCode} ${st.ref} | ${st.text} |`);
          continue;
        }
        const k = `${c.subject}|${st.outcomeCode}|${st.ref}`;
        uses.set(k, [...(uses.get(k) ?? []), `${c.id}: ${where}`]);
      }
    };
    c.lesson.forEach((s, i) => s.blocks.forEach((b) => 'covers' in b && note(b.covers, `step ${i + 1} ${b.type}`)));
    c.problems.forEach((p) => note(p.covers, `problem ${p.id}`));
    c.keyTerms.forEach((t) => note(t.covers, `term "${t.term}"`));
  }

  const lines: string[] = [
    `# Grade ${GRADE} ${s.name}: curriculum audit`,
    '',
    `Generated by \`npm run audit\`. Every statement from the Grade ${GRADE} program of studies is listed with the`,
    'lesson steps, problems and key terms that teach it. ✓ = taught, · = not taught yet.',
    'A page may only contain content that traces to a statement here (or a labelled earlier-grade recall).',
    '',
  ];
  let total = 0;
  let taught = 0;
  {
    for (const o of allOutcomes(GRADE, s.slug)) {
      const sts = outcomeStatements(GRADE, s.slug, o.code);
      const covered = sts.filter((st) => uses.has(`${s.slug}|${o.code}|${st.ref}`)).length;
      total += sts.length;
      taught += covered;
      lines.push(`## ${o.organizingIdea.title}: ${o.outcome}`, '', `\`${o.code}\` · ${covered}/${sts.length} statements taught`, '');
      if (!covered) continue;
      lines.push('| | Ref | Statement | Taught in |', '|---|---|---|---|');
      for (const st of sts) {
        const where = uses.get(`${s.slug}|${o.code}|${st.ref}`);
        const text = (st.text + (st.items ? ` (${st.items.join('; ')})` : '')).replace(/\|/g, '\\|');
        lines.push(`| ${where ? '✓' : '·'} | ${st.ref} | ${text} | ${where ? where.join('<br>') : ''} |`);
      }
      lines.push('');
    }
  }
  lines.push('## Earlier-grade recalls', '', 'Short reminders of what students learned before, used as stepping stones.', '');
  lines.push('| Page | Where | Statement | Text |', '|---|---|---|---|', ...earlier, '');
  lines.splice(6, 0, `**${taught} of ${total} Grade ${GRADE} ${s.shortName} statements are taught so far.**`, '');
  const file = `docs/curriculum-audit/grade-${GRADE}-${s.slug}.md`;
  writeFileSync(file, lines.join('\n'));
  console.log(`${file}: ${taught}/${total} statements taught, ${earlier.length} earlier-grade recalls`);
}
